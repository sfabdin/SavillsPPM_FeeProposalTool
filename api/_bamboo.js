/* BambooHR → the org chart. One custom report, current employees only,
   normalised to what the staffing store keeps: who, their work email, title,
   department, and who they report to (by email). Underscore-prefixed files
   in api/ are not routes.

   ENV  BAMBOO_SUBDOMAIN  the company's BambooHR subdomain (the part before
                          .bamboohr.com)
        BAMBOO_API_KEY    an API key generated by a BambooHR user who can see
                          the directory (Account → API Keys). It is sent as the
                          basic-auth username with any password.

   The custom report is POST /v1/reports/custom?format=JSON with the field
   list below. BambooHR returns one row per employee with every field keyed
   by its id; fields the account does not expose come back null. */
export class BambooError extends Error { constructor(status, detail) { super('BambooHR ' + status); this.status = status; this.detail = detail; } }

export const ORG_FIELDS = ['id', 'displayName', 'firstName', 'lastName', 'preferredName', 'workEmail', 'jobTitle', 'department', 'division', 'location', 'supervisor', 'supervisorId', 'supervisorEId', 'supervisorEmail', 'status', 'hireDate', 'employmentHistoryStatus'];

export function bambooConfigured() { return !!(process.env.BAMBOO_SUBDOMAIN && process.env.BAMBOO_API_KEY); }

export async function fetchOrg(opts) {
  const o = opts || {}; const sub = o.subdomain || process.env.BAMBOO_SUBDOMAIN, key = o.key || process.env.BAMBOO_API_KEY;
  if (!sub || !key) throw Object.assign(new Error('BambooHR not configured — set BAMBOO_SUBDOMAIN and BAMBOO_API_KEY.'), { code: 501 });
  const t0 = Date.now();
  const url = 'https://api.bamboohr.com/api/gateway.php/' + encodeURIComponent(sub) + '/v1/reports/custom?format=JSON&onlyCurrent=true';
  const r = await fetch(url, { method: 'POST', headers: { Authorization: 'Basic ' + Buffer.from(key + ':x').toString('base64'), Accept: 'application/json', 'Content-Type': 'application/json' },
    body: JSON.stringify({ title: 'PPM org chart', fields: ORG_FIELDS }) });
  if (!r.ok) throw new BambooError(r.status, (await r.text()).slice(0, 300));
  const j = await r.json();
  return normalizeOrg(j, { pulledAt: new Date().toISOString(), elapsedMs: Date.now() - t0 });
}
/** The report → the drop. Exported so the shape is testable without BambooHR. */
export function normalizeOrg(report, meta) {
  const rows = (report && report.employees) || [];
  const low = (v) => String(v || '').trim().toLowerCase();
  const byId = {}; rows.forEach(e => { byId[String(e.id)] = e; });
  const people = rows.map(e => {
    const supId = String(e.supervisorEId || e.supervisorId || '');
    const sup = byId[supId];
    return {
      id: String(e.id || ''), name: String(e.displayName || [e.preferredName || e.firstName, e.lastName].filter(Boolean).join(' ')).trim(),
      email: low(e.workEmail), title: String(e.jobTitle || '').trim(), department: String(e.department || '').trim(), division: String(e.division || '').trim(), location: String(e.location || '').trim(),
      supervisorId: supId, supervisor: String(e.supervisor || (sup && sup.displayName) || '').trim(), supervisorEmail: low(e.supervisorEmail || (sup && sup.workEmail)),
      status: String(e.status || e.employmentHistoryStatus || '').trim(), hireDate: String(e.hireDate || '').slice(0, 10),
    };
  }).filter(p => p.email || p.name);
  return Object.assign({ source: 'bamboohr', count: people.length, withEmail: people.filter(p => p.email).length, withSupervisor: people.filter(p => p.supervisorEmail).length, people }, meta || {});
}
